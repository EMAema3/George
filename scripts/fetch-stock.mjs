#!/usr/bin/env node
/**
 * Build-time stock photo fetch.
 * Downloads every image in src/data/stock.mjs from Unsplash (brightened + warmed
 * via imgix params) into public/images/stock/ with SEO filenames, in 3 sizes.
 * Also (re)writes public/_redirects so any file that failed to download is
 * proxied from Unsplash under the same URL — the site never shows a broken image.
 *
 * Never fails the build: a network problem just means the proxy fallback is used.
 */
import { mkdir, writeFile, stat, readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { stock, STOCK_PARAMS, STOCK_SIZES } from '../src/data/stock.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'public/images/stock');
await mkdir(outDir, { recursive: true });

const unsplashUrl = (id, w, h) => `https://images.unsplash.com/${id}?w=${w}&h=${h}&${STOCK_PARAMS}`;

const jobs = [];
for (const [name, { id }] of Object.entries(stock)) {
  for (const s of STOCK_SIZES) {
    jobs.push({ file: path.join(outDir, `${name}${s.suffix}.webp`), url: unsplashUrl(id, s.w, s.h), publicPath: `/images/stock/${name}${s.suffix}.webp` });
  }
}

async function fetchOne(job, attempt = 1) {
  if (existsSync(job.file)) {
    try { if ((await stat(job.file)).size > 2000) return 'cached'; } catch {}
  }
  try {
    const ctl = new AbortController();
    const timer = setTimeout(() => ctl.abort(), 20000);
    const res = await fetch(job.url, { signal: ctl.signal });
    clearTimeout(timer);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length < 2000) throw new Error('too small');
    await writeFile(job.file, buf);
    return 'ok';
  } catch (e) {
    if (attempt < 3) return fetchOne(job, attempt + 1);
    return 'fail';
  }
}

let ok = 0, cached = 0, fail = 0;
const queue = [...jobs];
await Promise.all(Array.from({ length: 8 }, async () => {
  while (queue.length) {
    const j = queue.shift();
    const r = await fetchOne(j);
    if (r === 'ok') ok++; else if (r === 'cached') cached++; else fail++;
  }
}));
console.log(`[stock] ${ok} downloaded, ${cached} cached, ${fail} unavailable (proxy fallback) — ${jobs.length} files`);

// Proxy fallback rules (non-forced: only used when the static file is absent)
const header = '# AUTO-GENERATED by scripts/fetch-stock.mjs — stock photo fallbacks + site redirects\n';
const siteRules = [
  '/guide  /aruba/  301',
  '/guide/  /aruba/  301',
];
const proxyRules = jobs.map((j) => `${j.publicPath}  ${j.url}  200`);
await writeFile(path.join(root, 'public/_redirects'), header + siteRules.join('\n') + '\n' + proxyRules.join('\n') + '\n');
